package com.corejava.basics;

public class ForLoopExample {

	public static void main(String[] args) {
		// Print the greeting once for each loop iteration.
		for(int i = 0; i < 10; i++) {
			System.out.println("hello world");
		}
		int i =0;
		while(i < 10) {
			System.out.println("hello world1");
			i++;
		}

	}

}
